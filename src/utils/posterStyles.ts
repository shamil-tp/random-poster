/**
 * Reusable Hybrid Design Generator Function:
 * Combines two distinct styles from the 50 design styles into a new cohesive hybrid specification.
 * Style A supplies the canvas palette, surface hierarchy, and primary SVG motif;
 * Style B supplies the typographic voice, structural layout variant, border treatment, and micro-interaction.
 */
export function createHybridDesignStyle(
  styleA: DesignStyleSpec,
  styleB: DesignStyleSpec,
  editionNumber: number = 1
): GeneratedPosterStyle {
  if (styleA.id === styleB.id) {
    return {
      ...styleA,
      signatureId: `pure-${styleA.id}`,
      isHybrid: false,
      parentStyles: [styleA],
      editionNumber,
    };
  }

  return {
    id: styleA.id * 100 + styleB.id,
    name: `${styleA.name} × ${styleB.name}`,
    slug: `${styleA.slug}-x-${styleB.slug}`,
    description: `Hybrid synthesis fusing ${styleA.name} (${styleA.mood.toLowerCase()} palette & ${styleA.motif.replace(/-/g, ' ')}) with ${styleB.name} (${styleB.layoutVariant.replace(/-/g, ' ')} structure & ${styleB.microInteractionLabel}).`,
    coreElements: [
      ...styleA.coreElements.slice(0, 2),
      ...styleB.coreElements.slice(0, 2),
    ],
    mood: `${styleA.mood.split(',')[0]} × ${styleB.mood.split(',')[0]}`,
    isDark: styleA.isDark,
    bgCanvas: styleA.bgCanvas,
    bgSurface: styleA.bgSurface,
    bgElevated: styleA.bgElevated,
    textPrimary: styleA.textPrimary,
    textSecondary: styleA.textSecondary,
    accentPrimary: styleA.accentPrimary,
    accentSecondary: styleB.accentPrimary,
    borderColor: styleA.borderColor,
    borderStyle: styleB.borderStyle,
    fontDisplay: styleB.fontDisplay,
    fontBody: styleA.fontBody,
    fontMono: styleB.fontMono,
    layoutVariant: styleB.layoutVariant,
    motif: styleA.motif,
    microInteraction: styleB.microInteraction,
    microInteractionLabel: `${styleB.microInteractionLabel} (${styleA.name} Field)`,
    photoTreatment: styleB.photoTreatment,
    signatureId: `hybrid-${styleA.id}-${styleB.id}`,
    isHybrid: true,
    parentStyles: [styleA, styleB],
    editionNumber,
  };
}

export interface PosterGenerationRecipe {
  style: GeneratedPosterStyle;
  projectIndex: number;
  secondaryProjectIndex: number;
  experienceIndex: number;
  hackathonIndex: number;
  skillGroupIndex: number;
  educationIndex: number;
  photoIndex: number;
  comboSignature: string;
}

/**
 * Generates a guaranteed non-repeating poster configuration given a Set/Array of already seen signatures.
 * Alternates between pure styles from the 50 catalog and synthesized 2-style hybrids so the user experiences
 * both authentic individual styles and endless hybrid combinations without ever seeing the same poster twice.
 */
export function generateUniquePosterRecipe(
  seenSignatures: string[],
  options?: {
    forceStyleId?: number;
    forceSecondaryStyleId?: number;
    forceHybrid?: boolean;
    projectCount?: number;
    photoCount?: number;
    seedOffset?: number;
    previousProjectIndex?: number;
    previousPhotoIndex?: number;
    previousStyleSignature?: string;
  }
): PosterGenerationRecipe {
  const seenSet = new Set(seenSignatures);
  const totalStyles = DESIGN_STYLES_50.length;
  const projectCount = options?.projectCount || 12;
  const photoCount = options?.photoCount || 3;
  const editionNumber = seenSignatures.length + 1;

  // Deterministic or pseudo-random stepping that searches for an unseen signature
  let attempt = 0;
  const baseSeed =
    options?.seedOffset !== undefined
      ? options.seedOffset
      : Math.floor(Math.random() * 100000) + editionNumber * 37;

  while (attempt < 500) {
    const step = baseSeed + attempt * 17;

    let styleA: DesignStyleSpec;
    let styleB: DesignStyleSpec | null = null;

    if (options?.forceStyleId) {
      styleA =
        DESIGN_STYLES_50.find((s) => s.id === options.forceStyleId) ||
        DESIGN_STYLES_50[0];
      if (options.forceSecondaryStyleId && options.forceSecondaryStyleId !== styleA.id) {
        styleB =
          DESIGN_STYLES_50.find((s) => s.id === options.forceSecondaryStyleId) ||
          null;
      } else if (options.forceHybrid) {
        const bIdx = (styleA.id + step + 7) % totalStyles;
        styleB = DESIGN_STYLES_50[bIdx === styleA.id - 1 ? (bIdx + 1) % totalStyles : bIdx];
      }
    } else {
      // Every 3rd edition (or if forceHybrid is true) synthesize a 2-style Hybrid Combo;
      // otherwise pick an unseen Pure Style from the 50 styles
      const useHybrid = options?.forceHybrid ?? (editionNumber % 3 === 0 || attempt > 50);
      const aIdx = (step * 13 + editionNumber * 7) % totalStyles;
      styleA = DESIGN_STYLES_50[aIdx];

      if (useHybrid) {
        const bIdx = (aIdx + 11 + (step % 23)) % totalStyles;
        styleB = DESIGN_STYLES_50[bIdx === aIdx ? (bIdx + 1) % totalStyles : bIdx];
      }
    }

    const generatedStyle: GeneratedPosterStyle = styleB
      ? createHybridDesignStyle(styleA, styleB, editionNumber)
      : {
          ...styleA,
          signatureId: `pure-${styleA.id}`,
          isHybrid: false,
          parentStyles: [styleA],
          editionNumber,
        };

    let projectIndex = (step + editionNumber * 5) % projectCount;
    if (
      options?.previousProjectIndex !== undefined &&
      projectCount > 1 &&
      projectIndex === options.previousProjectIndex
    ) {
      projectIndex = (projectIndex + 1) % projectCount;
    }

    const secondaryProjectIndex = (projectIndex + 5 + (step % 7)) % projectCount;

    let photoIndex = (editionNumber - 1 + attempt) % photoCount;
    if (
      options?.previousPhotoIndex !== undefined &&
      photoCount > 1 &&
      photoIndex === options.previousPhotoIndex
    ) {
      photoIndex = (photoIndex + 1) % photoCount;
    }

    const experienceIndex = (editionNumber + step) % 2;
    const hackathonIndex = (editionNumber * 2 + step) % 5;
    const skillGroupIndex = (editionNumber + step * 3) % 6;
    const educationIndex = editionNumber % 2;

    const comboSignature = `${generatedStyle.signatureId}::proj-${projectIndex}::photo-${photoIndex}`;

    const isSameStyleAsPrev =
      options?.previousStyleSignature !== undefined &&
      options?.forceStyleId === undefined &&
      generatedStyle.signatureId === options.previousStyleSignature;

    if (
      (!seenSet.has(comboSignature) && !isSameStyleAsPrev) ||
      options?.forceStyleId !== undefined
    ) {
      return {
        style: generatedStyle,
        projectIndex,
        secondaryProjectIndex:
          secondaryProjectIndex === projectIndex
            ? (projectIndex + 1) % projectCount
            : secondaryProjectIndex,
        experienceIndex,
        hackathonIndex,
        skillGroupIndex,
        educationIndex,
        photoIndex,
        comboSignature,
      };
    }

    attempt++;
  }

  // Fallback guaranteed unique signature
  const fallbackStyleA = DESIGN_STYLES_50[editionNumber % totalStyles];
  const fallbackStyleB = DESIGN_STYLES_50[(editionNumber + 19) % totalStyles];
  const fallbackStyle = createHybridDesignStyle(fallbackStyleA, fallbackStyleB, editionNumber);
  return {
    style: fallbackStyle,
    projectIndex: editionNumber % projectCount,
    secondaryProjectIndex: (editionNumber + 3) % projectCount,
    experienceIndex: editionNumber % 2,
    hackathonIndex: editionNumber % 5,
    skillGroupIndex: editionNumber % 6,
    educationIndex: editionNumber % 2,
    photoIndex: editionNumber % photoCount,
    comboSignature: `${fallbackStyle.signatureId}::ed-${editionNumber}`,
  };
}
